"""Long-path-safe replacement for `tree . /f /a`.

MAX_PATH-bound enumerators (Windows `tree.exe`, `dir /s`, plain os.walk without
the extended prefix) silently skip entries whose full path exceeds 260 chars.
This walks with the \\?\ prefix so nothing is dropped, and mirrors tree.exe's ASCII
layout closely enough to diff against an existing export.

Usage:  python generate_tree.py [root] [output filename]
        root defaults to the folder this script lives in;
        output defaults to "<root folder name> tree.txt" next to the root.
"""
import os
import sys

SKIP_DIR_NAMES = {'$RECYCLE.BIN', 'System Volume Information'}
MAX_DEPTH = 12


def extended(p):
    """\\?\ prefixed absolute path -> immune to the 260-char MAX_PATH limit."""
    ap = os.path.abspath(p)
    if ap.startswith('\\\\'):
        return '\\\\?\\UNC\\' + ap[2:]
    return '\\\\?\\' + ap


def scan_path(path):
    """Re-applying the prefix to an already-prefixed path breaks recursion silently."""
    return path if path.startswith('\\\\?\\') else extended(path)


def render(root, out):
    out.append('Folder PATH listing (generated by generate_tree.py)')
    out.append(root.rstrip('\\') or '\\')
    count = [0]

    def walk(path, prefix, depth):
        if depth > MAX_DEPTH:
            return
        try:
            with os.scandir(scan_path(path)) as it:
                entries = sorted(it, key=lambda e: e.name.lower())
        except OSError:
            return
        dirs = [e for e in entries if e.is_dir(follow_symlinks=False) and e.name not in SKIP_DIR_NAMES]
        files = [e for e in entries if e not in dirs]
        items = sorted(dirs + files, key=lambda e: e.name.lower())
        for i, e in enumerate(items):
            last = i == len(items) - 1
            branch = '\\---' if last else '+---'
            if e in dirs:
                out.append(prefix + branch + e.name)
                walk(e.path, prefix + ('    ' if last else '|   '), depth + 1)
            else:
                out.append(prefix + '    ' + e.name)
                count[0] += 1

    walk(root, '', 1)
    return count[0]


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    name = sys.argv[2] if len(sys.argv) > 2 else (os.path.basename(root.rstrip('\\')) or 'root') + ' tree.txt'
    dest = os.path.join(root, name)
    out = []
    n = render(root, out)
    with open(dest, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{n} files listed -> {dest}')


if __name__ == '__main__':
    main()
